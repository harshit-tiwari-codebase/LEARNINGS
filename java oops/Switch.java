public class Switch {
    public static void main(String[] args) {
        
        int day = 2;

        switch (day) {
            case 1:
                System.out.println("hello i am 1");
                break;
            case 2:
                System.out.println("hello i am 2");
                break;
            default:
                System.out.println("hello i am default");
                break;
        }
    }
}
